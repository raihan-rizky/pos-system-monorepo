const categoryIconNames = new Set(CATEGORY_ICON_OPTIONS.map(({ id }) => id));

export function isCategoryIconName(value: string): boolean {
  return categoryIconNames.has(value);
}

export function searchCategoryIcons(query: string, group?: string): readonly CategoryIconOption[] {
  const terms = query.trim().toLocaleLowerCase("id-ID").split(/\s+/).filter(Boolean);
  return CATEGORY_ICON_OPTIONS.filter((option) => {
    if (group && option.group !== group) return false;
    const searchable = [option.id, option.label, option.group, option.keywords].join(" ").toLocaleLowerCase("id-ID");
    return terms.every((term) => searchable.includes(term));
  });
}
